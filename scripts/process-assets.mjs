/**
 * process-assets.mjs — turn the raw v3 inputs into the shipped asset set (plan 10 S4,
 * formats from _templates/spikes/RESULTS.md "Asset formats S4 should use"):
 *   GLB + KHR_mesh_quantization + EXT_meshopt_compression, textures KTX2
 *   (ETC1S for colour and roughness/ORM, UASTC + zstd for normal maps), content-hashed names.
 *
 *   node scripts/process-assets.mjs [--only polyhaven,textures,own,characters] [--id <assetId>]
 *
 * Inputs:  data/raw/polyhaven/** (scripts/fetch-assets.mjs), data/raw/own/*.glb and
 *          data/raw/characters/*.glb (Blender exports from scripts/blender/), data/raw/decals/*.png
 *          (scripts/make-decals.mjs).
 * Outputs: public/assets/v3/{models,tex,characters}/ and public/assets/v3/manifest.json.
 * Tools:   toktx 4.4.2 (KTX-Software, ~/ktx-software/bin or PATH), ImageMagick `magick`.
 */
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, KHRTextureBasisu } from '@gltf-transform/extensions';
import { dedup, prune, weld, quantize, meshopt, getBounds, resample } from '@gltf-transform/functions';
import { MeshoptEncoder, MeshoptDecoder } from 'meshoptimizer';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, unlinkSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const RAW = join(root, 'data', 'raw');
const OUT = join(root, 'public', 'assets', 'v3');
const cfg = JSON.parse(readFileSync(join(root, 'scripts', 'assets', 'third-party.json'), 'utf8'));
const fetchLog = existsSync(join(RAW, 'fetch-log.json')) ? JSON.parse(readFileSync(join(RAW, 'fetch-log.json'), 'utf8')) : { items: {} };
const arg = (k) => { const i = process.argv.indexOf(k); return i > 0 ? process.argv[i + 1] : null; };
const only = arg('--only') ? new Set(arg('--only').split(',')) : null;
const onlyId = arg('--id');
const want = (k) => !only || only.has(k);
const TOKTX = [join(homedir(), 'ktx-software/bin/toktx'), '/usr/local/bin/toktx'].find(existsSync) || 'toktx';

/** Max texture size per Poly Haven model (most props are seen from a few metres). */
const MODEL_TEX = { rollershutter_door: 1024, metal_office_desk: 1024, cardboard_box_01: 1024, default: 512 };
/** Normal maps (UASTC) cost about 4x an ETC1S map of the same size, so they ship at half the colour size. */
const normalSize = (size) => Math.max(256, size / 2);

await MeshoptDecoder.ready; await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.decoder': MeshoptDecoder, 'meshopt.encoder': MeshoptEncoder });
const manifestPath = join(OUT, 'manifest.json');
const manifest = existsSync(manifestPath) ? JSON.parse(readFileSync(manifestPath, 'utf8')) : { about: '', assets: {} };
manifest.about = 'v3 asset set (plan 10 S4). Generated by scripts/process-assets.mjs; licences and authors from data/raw/fetch-log.json and ATTRIBUTION.md. sizeM is the bounding box in metres [x, y, z], y up.';

const hash = (buf) => createHash('sha256').update(buf).digest('hex').slice(0, 10);
const tmp = join(tmpdir(), `hh-assets-${process.pid}`);
mkdirSync(tmp, { recursive: true });

/** Encode one image buffer to KTX2. kind: 'color' | 'linear' | 'normal'. */
function toKtx2(buf, ext, kind, maxSize) {
  const src = join(tmp, `in-${hash(buf)}.${ext === 'image/png' ? 'png' : 'jpg'}`);
  const png = join(tmp, `rs-${hash(buf)}-${maxSize}.png`);
  const out = join(tmp, `out-${hash(buf)}-${kind}-${maxSize}.ktx2`);
  writeFileSync(src, buf);
  // Resize down only, to a power of two (basis needs multiples of 4; PoT keeps mipmaps simple).
  const [w, h] = execFileSync('magick', ['identify', '-format', '%w %h', src]).toString().split(' ').map(Number);
  const pot = (n) => 2 ** Math.round(Math.log2(n));
  const tw = Math.min(maxSize, pot(w)), th = Math.min(maxSize, pot(h));
  execFileSync('magick', [src, '-resize', `${tw}x${th}!`, ...(kind === 'color' ? [] : ['-colorspace', 'sRGB']), png]);
  const common = ['--t2', '--genmipmap'];
  const enc = kind === 'normal'
    ? ['--encode', 'uastc', '--uastc_quality', '2', '--uastc_rdo_l', '3', '--zcmp', '20', '--assign_oetf', 'linear']
    : ['--encode', 'etc1s', '--clevel', '4', '--qlevel', kind === 'color' ? '200' : '160', '--assign_oetf', kind === 'color' ? 'srgb' : 'linear'];
  execFileSync(TOKTX, [...common, ...enc, out, png], { stdio: ['ignore', 'ignore', 'pipe'] });
  const res = readFileSync(out);
  for (const f of [src, png, out]) try { unlinkSync(f); } catch {}
  return { buf: res, width: tw, height: th };
}

function textureKinds(doc) {
  const kinds = new Map();
  const mark = (t, k) => { if (t && !kinds.has(t)) kinds.set(t, k); };
  for (const m of doc.getRoot().listMaterials()) {
    mark(m.getBaseColorTexture(), 'color');
    mark(m.getEmissiveTexture(), 'color');
    mark(m.getNormalTexture(), 'normal');
    mark(m.getMetallicRoughnessTexture(), 'linear');
    mark(m.getOcclusionTexture(), 'linear');
  }
  return kinds;
}

async function compressDoc(doc, maxTex, { keepNames = false } = {}) {
  const basisu = doc.createExtension(KHRTextureBasisu).setRequired(true);
  void basisu;
  const kinds = textureKinds(doc);
  for (const tex of doc.getRoot().listTextures()) {
    const mime = tex.getMimeType();
    if (mime === 'image/ktx2') continue;
    const kind = kinds.get(tex) || 'color';
    const limit = typeof maxTex === 'function' ? maxTex(tex, kind) : (kind === 'normal' ? normalSize(maxTex) : maxTex);
    const { buf } = toKtx2(Buffer.from(tex.getImage()), mime, kind, limit);
    tex.setImage(new Uint8Array(buf)).setMimeType('image/ktx2');
    if (tex.getURI()) tex.setURI(tex.getURI().replace(/\.(png|jpe?g)$/i, '.ktx2'));
  }
  await doc.transform(
    dedup(),
    ...(doc.getRoot().listAnimations().length ? [resample()] : []),
    prune({ keepAttributes: false, keepLeaves: keepNames }),
    weld(),
    quantize({ quantizeNormal: 8, quantizePosition: 14, quantizeTexcoord: 12 }),
    meshopt({ encoder: MeshoptEncoder, level: 'high' }),
  );
  return doc;
}

function stats(doc) {
  let tris = 0;
  for (const mesh of doc.getRoot().listMeshes()) for (const p of mesh.listPrimitives()) {
    const idx = p.getIndices();
    tris += idx ? idx.getCount() / 3 : p.getAttribute('POSITION').getCount() / 3;
  }
  const scene = doc.getRoot().getDefaultScene() || doc.getRoot().listScenes()[0];
  const b = getBounds(scene);
  const size = b.max.map((v, i) => +(v - b.min[i]).toFixed(3));
  return { triangles: Math.round(tris), sizeM: size, textures: doc.getRoot().listTextures().length, animations: doc.getRoot().listAnimations().map((a) => a.getName()) };
}

async function writeGlb(doc, dir, name) {
  mkdirSync(join(OUT, dir), { recursive: true });
  const glb = Buffer.from(await io.writeBinary(doc));
  for (const f of readdirSync(join(OUT, dir))) if (new RegExp(`^${name}-[0-9a-f]{10}\\.glb$`).test(f)) rmSync(join(OUT, dir, f));
  const file = `${dir}/${name}-${hash(glb)}.glb`;
  writeFileSync(join(OUT, file), glb);
  return { file: `assets/v3/${file}`, bytes: glb.length };
}

// ---------- Poly Haven models ----------
if (want('polyhaven')) {
  for (const { id, use } of cfg.polyhavenModels) {
    if (onlyId && onlyId !== id) continue;
    const gltf = join(RAW, 'polyhaven', 'models', id, `${id}.gltf`);
    if (!existsSync(gltf)) { console.warn(`skip ${id}: run scripts/fetch-assets.mjs first`); continue; }
    const doc = await io.read(gltf);
    // Some Poly Haven models carry an alternative variant as a second node (the roller door has
    // a graffiti copy); keep the plain one. prune() then drops the unused mesh and textures.
    for (const node of doc.getRoot().listNodes()) if (/graffiti/i.test(node.getName())) node.dispose();
    await compressDoc(doc, MODEL_TEX[id] || MODEL_TEX.default);
    const s = stats(doc);
    const w = await writeGlb(doc, 'models', id);
    const lic = fetchLog.items[`model:${id}`] || {};
    manifest.assets[id] = { kind: 'polyhaven-model', use, ...w, ...s, name: lic.name, authors: lic.authors, source: lic.source || `https://polyhaven.com/a/${id}`, licence: 'CC0-1.0' };
    console.log(`${id}: ${(w.bytes / 1024).toFixed(0)} KB, ${s.triangles} tris, ${s.sizeM.join(' x ')} m`);
  }
}

// ---------- Standalone tiling textures ----------
if (want('textures')) {
  for (const { id, res, use } of cfg.polyhavenTextures) {
    if (onlyId && onlyId !== id) continue;
    const dir = join(RAW, 'polyhaven', 'textures', id);
    if (!existsSync(dir)) { console.warn(`skip ${id}`); continue; }
    const maps = {};
    for (const [name, kind] of [['diff', 'color'], ['nor_gl', 'normal'], ['rough', 'linear'], ['arm', 'linear']]) {
      const src = join(dir, `${id}_${name}_${res}.jpg`);
      if (!existsSync(src)) continue;
      if (id === 'blue_metal_plate' && name === 'diff') continue; // tinted per use in code; colour map not kept (as in v2)
      if (name === 'rough' && existsSync(join(dir, `${id}_arm_${res}.jpg`))) continue; // ARM carries roughness in G
      const size = name === 'nor_gl' ? (res === '2k' ? 1024 : 512) : (res === '2k' ? 2048 : 1024);
      const { buf, width } = toKtx2(readFileSync(src), 'image/jpeg', kind, size);
      mkdirSync(join(OUT, 'tex'), { recursive: true });
      for (const f of readdirSync(join(OUT, 'tex'))) if (new RegExp(`^${id}_${name}-[0-9a-f]{10}\\.ktx2$`).test(f)) rmSync(join(OUT, 'tex', f));
      const file = `tex/${id}_${name}-${hash(buf)}.ktx2`;
      writeFileSync(join(OUT, file), buf);
      maps[name] = { file: `assets/v3/${file}`, bytes: buf.length, size: width, colorSpace: kind === 'color' ? 'srgb' : 'linear' };
    }
    const lic = fetchLog.items[`texture:${id}`] || {};
    manifest.assets[`tex:${id}`] = { kind: 'polyhaven-texture', use, maps, authors: lic.authors, source: lic.source || `https://polyhaven.com/a/${id}`, licence: 'CC0-1.0', note: 'ARM = AO (R), roughness (G), metalness (B)' };
    console.log(`tex ${id}: ${Object.entries(maps).map(([k, v]) => `${k} ${v.size}px ${(v.bytes / 1024).toFixed(0)} KB`).join(', ')}`);
  }
}

// ---------- Own Blender work and characters ----------
for (const [group, dir, outDir, maxTex] of [['own', 'own', 'models', 1024], ['characters', 'characters', 'characters', 1024]]) {
  if (!want(group)) continue;
  const src = join(RAW, dir);
  if (!existsSync(src)) continue;
  const meta = existsSync(join(src, 'meta.json')) ? JSON.parse(readFileSync(join(src, 'meta.json'), 'utf8')) : {};
  for (const f of readdirSync(src).filter((n) => n.endsWith('.glb')).sort()) {
    const id = basename(f, '.glb');
    if (onlyId && onlyId !== id) continue;
    const doc = await io.read(join(src, f));
    const m = meta[id] || {};
    await compressDoc(doc, (tex, kind) => {
      const n = (tex.getName() || tex.getURI() || '').toLowerCase();
      if (group === 'characters') {
        if (/eye|brow|lash|teeth|tongue/.test(n)) return 256;
        if (kind === 'normal') return 512;
        return /skin|body|diffuse/.test(n) ? 1024 : 512;
      }
      // Shared tiling maps are embedded in many props: the painted-steel micro-surface maps
      // ship at 256 px and the wood/tread/panel maps at 512 px so props stay small.
      const lim = /blue_metal_plate/.test(n) ? 256 : /raw_plank|metal_plate|painted_metal_shutter|concrete_block/.test(n) ? 512 : (m.maxTex || maxTex);
      return kind === 'normal' && lim > 256 ? normalSize(lim) : lim;
    }, { keepNames: true });
    const s = stats(doc);
    const w = await writeGlb(doc, outDir, id);
    if (group === 'characters' && m.sizeM) s.sizeM = m.sizeM; // skinned bounds come from Blender (rest pose)
    manifest.assets[id] = { kind: group === 'own' ? 'own-blender' : 'mpfb-character', ...m, ...w, ...s, licence: group === 'own' ? 'own work (CC BY 4.0, repo content licence)' : 'CC0-1.0 inputs (MakeHuman system assets, MPFB base mesh); vest, hard hat and animation own work' };
    console.log(`${id}: ${(w.bytes / 1024).toFixed(0)} KB, ${s.triangles} tris, ${s.sizeM.join(' x ')} m${s.animations.length ? `, clips ${s.animations.join(', ')}` : ''}`);
  }
}

// ---------- Decal and sign textures (own work, scripts/make-decals.mjs) ----------
if (want('decals') && existsSync(join(RAW, 'decals'))) {
  const meta = existsSync(join(RAW, 'decals', 'meta.json')) ? JSON.parse(readFileSync(join(RAW, 'decals', 'meta.json'), 'utf8')) : {};
  mkdirSync(join(OUT, 'decals'), { recursive: true });
  for (const f of readdirSync(join(RAW, 'decals')).filter((n) => n.endsWith('.png')).sort()) {
    const id = basename(f, '.png');
    if (onlyId && onlyId !== id) continue;
    const m = meta[id] || {};
    const kind = m.kind === 'normal' ? 'normal' : (m.kind === 'linear' ? 'linear' : 'color');
    const { buf, width, height } = toKtx2(readFileSync(join(RAW, 'decals', f)), 'image/png', kind, m.maxSize || 1024);
    for (const g of readdirSync(join(OUT, 'decals'))) if (new RegExp(`^${id}-[0-9a-f]{10}\\.ktx2$`).test(g)) rmSync(join(OUT, 'decals', g));
    const file = `decals/${id}-${hash(buf)}.ktx2`;
    writeFileSync(join(OUT, file), buf);
    manifest.assets[`decal:${id}`] = { ...m, kind: 'own-decal', encoding: kind, file: `assets/v3/${file}`, bytes: buf.length, px: [width, height], licence: 'own work (CC BY 4.0, repo content licence)' };
    console.log(`decal ${id}: ${width}x${height}, ${(buf.length / 1024).toFixed(0)} KB`);
  }
}

manifest.assets = Object.fromEntries(Object.entries(manifest.assets).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
rmSync(tmp, { recursive: true, force: true });
console.log(`manifest: ${Object.keys(manifest.assets).length} entries`);
